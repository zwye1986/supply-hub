-- 吾盛会员免登进入 H5：平台配置与会员绑定表
-- 编码：UTF-8 without BOM

CREATE TABLE IF NOT EXISTS `mall_platform_config` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '编号',
  `tenant_id` bigint NOT NULL DEFAULT 0 COMMENT '绑定租户编号',
  `platform_code` varchar(32) NOT NULL COMMENT '平台编码，例如 WUSHENG',
  `platform_name` varchar(64) NOT NULL COMMENT '平台名称',
  `api_base_url` varchar(256) DEFAULT NULL COMMENT '外部平台接口地址',
  `app_id` varchar(128) NOT NULL DEFAULT '' COMMENT '外部平台应用 ID',
  `app_key` varchar(128) DEFAULT NULL COMMENT '外部平台应用 Key',
  `secret_key` varchar(256) DEFAULT NULL COMMENT '签名密钥，建议后续按项目加密策略保存',
  `sign_type` varchar(32) DEFAULT 'MD5' COMMENT '签名方式',
  `h5_base_url` varchar(256) NOT NULL COMMENT 'H5 基础地址',
  `timestamp_valid_seconds` int NOT NULL DEFAULT 600 COMMENT '请求时间戳有效秒数',
  `point_unit_name` varchar(32) NOT NULL DEFAULT '积分' COMMENT '积分单位展示名称，例如积分、元宝、金豆',
  `status` tinyint NOT NULL DEFAULT 1 COMMENT '状态：0 禁用，1 启用',
  `config_json` text DEFAULT NULL COMMENT '扩展配置 JSON',
  `remark` varchar(512) DEFAULT NULL COMMENT '备注',
  `creator` varchar(64) DEFAULT '' COMMENT '创建者',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `updater` varchar(64) DEFAULT '' COMMENT '更新者',
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  `deleted` bit(1) NOT NULL DEFAULT b'0' COMMENT '是否删除',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_platform_code` (`platform_code`),
  UNIQUE KEY `uk_tenant_platform_app` (`tenant_id`, `platform_code`, `app_id`),
  KEY `idx_platform_status` (`platform_code`, `status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='外部平台配置表';

CREATE TABLE IF NOT EXISTS `mall_platform_member_bind` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '编号',
  `tenant_id` bigint NOT NULL DEFAULT 0 COMMENT '租户编号',
  `platform_code` varchar(32) NOT NULL COMMENT '平台编码，例如 WUSHENG',
  `app_id` varchar(128) NOT NULL DEFAULT '' COMMENT '外部平台应用 ID',
  `external_member_id` varchar(128) NOT NULL COMMENT '外部会员编号，即吾盛 memberId',
  `member_user_id` bigint NOT NULL COMMENT '本地会员用户 ID，对应 member_user.id',
  `mobile` varchar(32) DEFAULT NULL COMMENT '外部平台传入手机号，可为空',
  `nickname` varchar(128) DEFAULT NULL COMMENT '外部平台传入昵称',
  `avatar` varchar(512) DEFAULT NULL COMMENT '外部平台传入头像',
  `external_member_snapshot` text DEFAULT NULL COMMENT '外部会员信息快照 JSON，便于联调排查',
  `bind_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '首次绑定时间',
  `last_login_time` datetime DEFAULT NULL COMMENT '最近免登时间',
  `last_login_ip` varchar(50) DEFAULT NULL COMMENT '最近免登 IP',
  `status` tinyint NOT NULL DEFAULT 1 COMMENT '状态：0 禁用，1 启用',
  `creator` varchar(64) DEFAULT '' COMMENT '创建者',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `updater` varchar(64) DEFAULT '' COMMENT '更新者',
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  `deleted` bit(1) NOT NULL DEFAULT b'0' COMMENT '是否删除',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_tenant_platform_member` (`tenant_id`, `platform_code`, `external_member_id`),
  KEY `idx_tenant_member_user` (`tenant_id`, `member_user_id`),
  KEY `idx_tenant_platform_app` (`tenant_id`, `platform_code`, `app_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='外部平台会员绑定表';
